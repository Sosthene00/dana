import 'package:bitcoin_ui/bitcoin_ui.dart';
import 'package:danawallet/generated/rust/api/bip39.dart';
import 'package:danawallet/generated/rust/api/structs/network.dart';
import 'package:danawallet/screens/onboarding/recovery/backup_file_restore_screen.dart';
import 'package:danawallet/screens/onboarding/recovery/descriptor_screen.dart';
import 'package:danawallet/screens/onboarding/recovery/seed_phrase.dart';
import 'package:danawallet/widgets/skeletons/screen_skeleton.dart';
import 'package:flutter/material.dart';

/// Restore-promise copy asymmetry (spec §7.2, normative): a file restore
/// returns "everything, exactly as it was" (funds + addresses + scan state
/// + history + labels; contacts/settings if present; no rescan), while a
/// seed restore returns "your bitcoin, not your history" (funds and
/// addresses only, then a rescan). This screen offers both paths side by
/// side, so the asymmetry MUST stay visible here.
const String fileRestorePromise =
    'Everything, exactly as it was — funds, addresses, history, labels and scan state. No rescan.';
const String seedRestorePromise =
    'Your bitcoin, not your history — funds and addresses only, then a rescan.';

class RestoreMethodScreen extends StatelessWidget {
  final Network network;

  const RestoreMethodScreen({super.key, required this.network});

  @override
  Widget build(BuildContext context) {
    final body = ListView(
      children: [
        ListTile(
          contentPadding: EdgeInsets.zero,
          leading: Icon(Icons.file_present_outlined, color: Bitcoin.blue),
          title: Text(
            'Backup file',
            style: BitcoinTextStyle.body3(Bitcoin.neutral8),
          ),
          subtitle: Text(
            fileRestorePromise,
            style: BitcoinTextStyle.body4(Bitcoin.neutral6),
          ),
          isThreeLine: true,
          trailing: Icon(Icons.chevron_right, color: Bitcoin.neutral6),
          onTap: () {
            Navigator.push(
              context,
              MaterialPageRoute(
                builder: (context) => BackupFileRestoreScreen(network: network),
              ),
            );
          },
        ),
        const Divider(),
        ListTile(
          contentPadding: EdgeInsets.zero,
          leading: Icon(Icons.key_outlined, color: Bitcoin.blue),
          title: Text(
            'Recovery phrase',
            style: BitcoinTextStyle.body3(Bitcoin.neutral8),
          ),
          subtitle: Text(
            '12 words generated by Dana. $seedRestorePromise',
            style: BitcoinTextStyle.body4(Bitcoin.neutral6),
          ),
          isThreeLine: true,
          trailing: Icon(Icons.chevron_right, color: Bitcoin.neutral6),
          onTap: () {
            Navigator.push(
              context,
              MaterialPageRoute(
                builder: (context) => SeedPhraseScreen(
                  bip39Words: getEnglishWordlist(),
                  network: network,
                ),
              ),
            );
          },
        ),
        const Divider(),
        ListTile(
          contentPadding: EdgeInsets.zero,
          leading: Icon(Icons.description_outlined, color: Bitcoin.blue),
          title: Text(
            'Descriptor',
            style: BitcoinTextStyle.body3(Bitcoin.neutral8),
          ),
          subtitle: Text(
            'Paste an sp() descriptor. $seedRestorePromise',
            style: BitcoinTextStyle.body4(Bitcoin.neutral6),
          ),
          isThreeLine: true,
          trailing: Icon(Icons.chevron_right, color: Bitcoin.neutral6),
          onTap: () {
            Navigator.push(
              context,
              MaterialPageRoute(
                builder: (context) => DescriptorRestoreScreen(network: network),
              ),
            );
          },
        ),
      ],
    );

    return ScreenSkeleton(
      title: 'Restore wallet',
      showBackButton: true,
      body: body,
    );
  }
}
